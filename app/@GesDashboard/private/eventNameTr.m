function s = eventNameTr(type, detail)
%EVENTNAMETR Olay kataloğu kodlarının Türkçe karşılığı (olaylar tablosu için).
types = dictionary( ...
    ["derating" "thermal_derating" "grid_event" "offline" "power_deficit" "string_dead" "string_weak" ...
     "string_fault" "trip" "inverter_trip" "meteo_sensor_suspect" "low_insulation" "reboot_event" ...
     "relay_cycling" "efficiency_drop" "soiling"], ...
    ["Isıl kısma / güç düşürme" "Isıl kısma / güç düşürme" "Şebeke/L1 olayı" "Veri yok / kesinti" ...
     "Açıklanamayan eksik" "DC dizi/akım kesintisi" "Zayıf dizi/akım" "DC dizi/MPPT anomalisi" ...
     "Evirici durması (trip)" "Evirici durması (trip)" "Sensör uyuşmazlığı şüphesi" ...
     "Düşük yalıtım direnci (R_iso)" "Yeniden başlatma (Reboot)" "Sabah/akşam k/18 röle çevrimi" ...
     "Evirici verim düşüşü" "Tozlanma / kirlenme"]);
details = dictionary( ...
    ["fault_status" "idle_no_dc" "zero_output" "voltage_sag_swell" "freq_deviation" "grid_loss" ...
     "dc_present_no_ac" "dc_disconnected" "efficiency_collapse" "current_step_drop" "voltage_drop" ...
     "bypass_short" "reboot_handshake" "morning_dew" "grid_voltage_rise"], ...
    ["arıza kodu" "DC gerilim var, akım yok (MPP/IGBT)" "çıkış sıfır" "L1 gerilim dalgalanması" ...
     "L1 frekans sapması" "gündüz tam şebeke kaybı" "DC var, AC çıkış sıfır" "DC bağlantı açık" ...
     "dönüşüm verimi çökmesi" "akım basamak düşüşü" "gerilim düşüşü (bypass diyot)" ...
     "bypass diyot kısa devresi" "0.00% set değeri reset/el-sıkışma" "sabah çiyi/nem kaynaklı R_iso" ...
     "L1 şebeke gerilim yükselmesi"]);
type = string(type);
detail = string(detail);
s = type;
k = isKey(types, type);
s(k) = types(type(k));
d = isKey(details, detail);
s(d) = s(d) + " (" + details(detail(d)) + ")";
v = ~d & detail ~= "" & ~ismissing(detail);
s(v) = s(v) + " (" + detail(v) + ")";
end
