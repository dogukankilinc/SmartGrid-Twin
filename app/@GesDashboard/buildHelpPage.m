function buildHelpPage(app, parent)
%BUILDHELPPAGE Yardım: sözlük (ges.agents.glossary — 4 Altın SmartGridLab yasası dahil), durumlar, sayfalar.
g = uigridlayout(parent, [1 1], Padding=[2 2 2 2]);
G = ges.agents.glossary();
esc = @(s) replace(replace(replace(string(s), "&", "&amp;"), "<", "&lt;"), ">", "&gt;");
items = strings(0, 1);
for k = 1:numel(G)
    items(end+1) = "<details" + ifelse(k <= 2, " open", "") + "><summary><b>" + esc(G(k).Term) + "</b> — " + ...
        esc(G(k).Short) + "</summary><p>" + esc(G(k).Long) + "</p></details>"; %#ok<AGROW>
end
st = ["ok" "watch" "thermal" "warning" "alarm" "chronic" "grid" "offline" "night"];
def = ["Üretim beklenene yakın (eksik < %5)." ...
    "Hafif sapma: en az 1 saattir %5–10 eksik, düşük R_iso (<1500 kΩ) ya da kısa süreli güç düşürme." ...
    "Sıcaklık veya MPP→Voc kayması nedeniyle güç kısılıyor (dV > +6%, dI < -8%)." ...
    "En az 1 saattir %10–15 eksik ya da DC dizi akım/gerilim düşüşü." ...
    "En az 1 saattir %15'ten fazla eksik, evirici durması (trip / DC var AC yok) ya da ciddi dizi kaybı." ...
    "Aynı uyarı/alarm 7 günden uzun sürüyor (bakım kaydı)." ...
    "L1 şebeke gerilimi/frekansı EN 50160 sınırları dışında ya da gündüz tam şebeke kaybı (U_L1 = 0 V)." ...
    "Bu adımda eviriciden veri gelmedi (ör. 27–31 Temmuz kesintisi)." ...
    "Güneş ufkun 5°'den az üzerinde."];
rows = strings(0, 1);
for k = 1:numel(st)
    rows(end+1) = "<tr><td><span class='dot' style='background:" + app.StateColor(st(k)) + "'></span>" + ...
        app.StateTr(st(k)) + "</td><td>" + esc(def(k)) + "</td></tr>"; %#ok<AGROW>
end
pages = strings(0, 1);
for k = 1:numel(app.Pages)
    pages(end+1) = "<tr><td>" + app.PageIcons(k) + " " + app.PageTitles(k) + "</td><td>" + esc(app.PageTopics(k)) + "</td></tr>"; %#ok<AGROW>
end
html = "<!DOCTYPE html><html lang='tr'><head><meta charset='utf-8'><style>" + ...
    "body{font-family:'Segoe UI',Arial,sans-serif;font-size:13px;color:#1f2933;margin:10px 16px;background:#f7f9fb}" + ...
    "h2{font-size:16px;margin:14px 0 6px}details{background:#fff;border:1px solid #dfe4ea;border-radius:6px;padding:6px 10px;margin:5px 0}" + ...
    "summary{cursor:pointer}p{margin:6px 0 2px;line-height:1.5}table{border-collapse:collapse;background:#fff}" + ...
    "td{border:1px solid #dfe4ea;padding:4px 8px;vertical-align:top}td:first-child{white-space:nowrap;font-weight:600}" + ...
    ".dot{display:inline-block;width:10px;height:10px;border-radius:2px;margin-right:6px}</style></head><body>" + ...
    "<h2>Sözlük & BTÜ SmartGridLab Mühendislik Kuralları</h2>" + strjoin(items, "") + ...
    "<h2>Harita durumları</h2><table>" + strjoin(rows, "") + "</table>" + ...
    "<h2>Sayfalar</h2><table>" + strjoin(pages, "") + "</table>" + ...
    "<p>Sağdaki asistan yalnızca açık sayfanın içeriğiyle yanıt verir; başka sayfadaki bilgi için yönlendirir. " + ...
    "📌 Hafızaya al ile bir sayfadaki bilgiyi saklayıp başka sayfada karşılaştırma isteyebilirsiniz.</p></body></html>";
app.Hp.Html = uihtml(g, HTMLSource=html);
app.Hp.Glossary = G;
end
