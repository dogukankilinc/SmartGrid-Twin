function o = emptyOpinion(key, name)
%EMPTYOPINION Görüş yapısının boş (çekimser / kullanılamaz) hali — üç görüşün ortak biçimi.
%   Key        : "sensor" | "visual" | "peer"
%   Available  : görüş bu gün için karar verebildi mi
%   Label      : birincil karar ("" = çekimser);  Labels: gördüğü tüm sorunlar (çok etiketli)
%   Confidence : görüşün kendi güveni (0..1)
%   Hard       : birincil karar deterministik bir ölçüme dayanıyor (yalnızca 1. görüş)
%   HardLabels : deterministik ölçüme dayanan sınıflar (şebeke, durum kodlu trip, tam string kaybı, ısıl kısma imzası)
%   Stance     : ges.opinions.classes() sırasıyla her sınıf için +1 destek, −1 çürütme, 0 göremez/çekimser
%   StringKind : 1. görüşte string kanıtının türü ("dead" | "voltage_drop" | "weak")
%   Evidence   : kısa kanıt metni
%   Uyumluluk alanları: Primary (= Label), Active (= Labels), Scores (1×6), Detail (= Evidence)
cls = ges.opinions.classes();
o = struct( ...
    "Key", string(key), ...
    "Name", string(name), ...
    "Available", false, ...
    "Label", "", ...
    "Labels", strings(1, 0), ...
    "Confidence", NaN, ...
    "Hard", false, ...
    "HardLabels", strings(1, 0), ...
    "Stance", zeros(1, numel(cls)), ...
    "StringKind", "", ...
    "Evidence", "", ...
    "Primary", "", ...
    "Active", strings(1, 0), ...
    "Scores", zeros(1, numel(cls)), ...
    "Detail", "");
end
